// Hand-rolled stroke icon set — replaces the emoji that made the UI read
// as generic. 24px viewBox, stroke = currentColor so icons inherit text
// color everywhere (incl. dark mode and brand-colored active states).
// No icon library dependency; add icons here as needed.

interface IconProps {
  size?: number;
  className?: string;
}

function Svg({
  size = 16,
  className = "",
  children,
}: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
    >
      {children}
    </svg>
  );
}

